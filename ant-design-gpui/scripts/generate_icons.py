#!/usr/bin/env python3
"""Generate the immutable Rust icon catalog from the vendored, pinned Ant SVGs."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
THEMES = ("outlined", "filled", "twotone")
SVG_NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG_NS)


def generate() -> dict[Path, str]:
    resources = ROOT / "resources" / "icons"
    lock = json.loads((resources / "upstream.lock.json").read_text(encoding="utf-8"))
    records: list[tuple[str, str, str, str]] = []
    output: dict[Path, str] = {}
    forbidden = {"script", "foreignObject", "iframe", "animate", "animateMotion", "animateTransform", "set"}
    counts: dict[str, int] = {}
    for theme in THEMES:
        sources = sorted((resources / "templates" / theme).glob("*.svg"))
        counts[theme] = len(sources)
        for source in sources:
            root = ET.fromstring(source.read_text(encoding="utf-8"))
            values = [float(value) for value in root.get("viewBox", "").split()]
            if len(values) != 4 or values[2] <= 0 or values[3] <= 0:
                raise ValueError(f"invalid viewBox: {source}")
            for element in root.iter():
                tag = element.tag.rsplit("}", 1)[-1]
                if tag in forbidden:
                    raise ValueError(f"active SVG element in {source}: {tag}")
                for attribute, value in element.attrib.items():
                    if attribute.rsplit("}", 1)[-1].lower().startswith("on"):
                        raise ValueError(f"SVG event handler in {source}")
                    if attribute.rsplit("}", 1)[-1] in {"href", "src"} and not value.startswith("#"):
                        raise ValueError(f"external SVG reference in {source}")
                slot = element.attrib.pop("data-adqt-slot", None)
                if slot == "secondary":
                    for attribute in ("fill", "stroke"):
                        if attribute in element.attrib and element.attrib[attribute] != "none":
                            element.set(attribute, "__ADGPUI_SECONDARY__")
                elif slot not in {None, "primary"}:
                    raise ValueError(f"unsupported color slot in {source}: {slot}")
            svg = ET.tostring(root, encoding="unicode").replace(" />", "/>") + "\n"
            if theme == "twotone" and "__ADGPUI_SECONDARY__" not in svg:
                raise ValueError(f"missing secondary color slot: {source}")
            symbol = "".join(part.capitalize() for part in source.stem.split("-"))
            variant = symbol + {"outlined": "Outlined", "filled": "Filled", "twotone": "TwoTone"}[theme]
            if variant[:1].isdigit():
                variant = "Icon" + variant
            relative = f"{theme}/{source.name}"
            output[resources / "generated" / relative] = svg
            records.append((variant, theme, source.stem, hashlib.sha256(svg.encode()).hexdigest()))
    expected = lock["counts"]
    if any(counts[theme] != expected[theme] for theme in THEMES):
        raise ValueError(f"icon counts do not match upstream lock: {counts}")
    if len({record[0] for record in records}) != len(records):
        raise ValueError("generated Rust icon identifiers collide")
    lines = [
        "// Copyright (C) 2026 mg-chao",
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by scripts/generate_icons.py. DO NOT EDIT.",
        "",
        "use super::{IconColorModel, IconDescriptor};",
        "",
        "/// A compile-time checked icon from the pinned upstream Ant Design catalog.",
        "#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]",
        "#[repr(u16)]",
        "pub enum IconName {",
    ]
    lines.extend(f"    {variant}," for variant, _, _, _ in records)
    lines.extend(["}", "", "impl IconName {", "    /// All built-in icons in deterministic variant/name order.", f"    pub const ALL: [Self; {len(records)}] = ["])
    lines.extend(f"        Self::{variant}," for variant, _, _, _ in records)
    lines.extend(["    ];", "", "    /// The immutable descriptor backing this icon.", "    pub const fn descriptor(self) -> &'static IconDescriptor {", "        &DESCRIPTORS[self as usize]", "    }", "", "    pub(super) const fn cache_path(self) -> &'static str {", "        CACHE_PATHS[self as usize]", "    }", "}", "", f"static CACHE_PATHS: [&str; {len(records)}] = ["])
    lines.extend(f'    "__adgpui__/antd/{theme}/{name}",' for _, theme, name, _ in records)
    lines.extend(["];", "", f"static DESCRIPTORS: [IconDescriptor; {len(records)}] = ["])
    for _, theme, name, _ in records:
        model = "TwoTone" if theme == "twotone" else "Monochrome"
        lines.extend([
            "    IconDescriptor {",
            f'        key: "antd/{theme}/{name}",',
            f"        color_model: IconColorModel::{model},",
            f'        svg: include_bytes!("../../resources/icons/generated/{theme}/{name}.svg"),',
            "    },",
        ])
    lines.extend([
        "];", "",
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "    #[test]",
        "    fn catalog_is_complete_and_unique() {",
        "        assert_eq!(IconName::ALL.len(), 829);",
        "        let mut keys = std::collections::HashSet::new();",
        "        for name in IconName::ALL {",
        "            assert!(keys.insert(name.descriptor().key));",
        "        }",
        "    }",
        "}", "",
    ])
    # rustfmt is deliberately part of generation, keeping --check byte-for-byte reproducible.
    import subprocess
    source = "\n".join(lines)
    formatted = subprocess.run(["rustfmt", "--edition", "2024", "--emit", "stdout"], input=source, text=True, capture_output=True, check=True, cwd=ROOT)
    output[ROOT / "src" / "icons" / "generated.rs"] = formatted.stdout
    manifest = {"upstream_commit": lock["resolved_commit"], "icons": [{"name": variant, "key": f"antd/{theme}/{name}", "sha256": digest} for variant, theme, name, digest in records]}
    output[resources / "catalog.json"] = json.dumps(manifest, indent=2) + "\n"
    return output


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated output is stale")
    args = parser.parse_args()
    output = generate()
    stale = []
    for path, content in output.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    expected_paths = set(output)
    generated = ROOT / "resources" / "icons" / "generated"
    if generated.exists():
        stale.extend(str(path.relative_to(ROOT)) for path in generated.rglob("*.svg") if path not in expected_paths)
    if stale:
        raise SystemExit("stale generated icons:\n" + "\n".join(stale))
    print(f"icons=829 outputs={len(output)} check={args.check}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
